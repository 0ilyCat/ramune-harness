import { execa } from 'execa';
import { mkdirSync, createWriteStream, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { finished } from 'node:stream/promises';
const [directory, label, command, ...args] = process.argv.slice(2);
if (!directory || !/^[a-z0-9-]+$/.test(label || '') || !command) throw new Error('参数：证据目录、英文标签、命令、参数');
const dir = resolve(directory); mkdirSync(dir, { recursive: true });
const stdoutPath = join(dir, `${label}.stdout.log`), stderrPath = join(dir, `${label}.stderr.log`);
const stdout = createWriteStream(stdoutPath, { mode: 0o600 }), stderr = createWriteStream(stderrPath, { mode: 0o600 });
const startedAt = new Date().toISOString();
const child = execa(command, args, { reject: false, buffer: false, windowsHide: true, killDescendants: true, timeout: 1200000 });
child.stdout?.on('data', chunk => { stdout.write(chunk); process.stdout.write(chunk); });
child.stderr?.on('data', chunk => { stderr.write(chunk); process.stderr.write(chunk); });
const result = await child; stdout.end(); stderr.end(); await Promise.all([finished(stdout), finished(stderr)]);
const digest = path => ({ path, bytes: readFileSync(path).length, sha256: createHash('sha256').update(readFileSync(path)).digest('hex') });
const record = { label, startedAt, finishedAt: new Date().toISOString(), command, args, cwd: process.cwd(), exitCode: result.exitCode ?? 1, stdout: digest(stdoutPath), stderr: digest(stderrPath) };
writeFileSync(join(dir, `${label}.command.json`), JSON.stringify(record, null, 2));
console.log(`QA_COMMAND_RESULT ${JSON.stringify(record)}`); process.exitCode = record.exitCode;
